#!/usr/bin/env python3
"""Compose the automatically translated SpaceWasm implementation with events.

The input is generated by `wasm2maude run` from the exact pinned SpaceWasm
library and the generic stateful driver.  This script does not model loader,
table, module, or interpreter behavior.  It only exposes three exported API
calls (`state_init`, `state_event`, `state_result`) as deterministic semantic
macro steps and adds a generic permutation scheduler plus a public property.
"""

from __future__ import annotations

import argparse
from pathlib import Path


def once(text: str, old: str, new: str) -> str:
    count = text.count(old)
    if count != 1:
        raise RuntimeError(f"expected exactly one occurrence, found {count}: {old!r}")
    return text.replace(old, new, 1)


def name_term(name: str) -> str:
    chars = " ".join(f"char.wrap({ord(ch)})" for ch in name)
    return f"name.wrap({chars})"


def transform(text: str) -> str:
    marker = "\nrew ["
    if marker not in text:
        raise RuntimeError("generated final rewrite command not found")
    text = text.split(marker, 1)[0].rstrip() + "\n"

    first_newline = text.find("\n")
    if first_newline < 0:
        raise RuntimeError("generated load command not found")
    text = (
        text[: first_newline + 1]
        + "load model-checker.maude\n\n"
        + text[first_newline + 1 :]
    )

    text = once(text, "mod WASM2MAUDE-RUN is", "mod SPACEWASM-STATEFUL-EVAL is")
    text = once(
        text,
        "  op exec : SpectecTerminal -> RunState [ctor frozen (1)] .",
        "  op exec : SpectecTerminal -> RunState [ctor frozen (1)] .\n"
        "  op prepared : SpectecTerminal SpectecTerminal -> RunState "
        "[ctor frozen (1 2)] .\n"
        "  op callInit : SpectecTerminal SpectecTerminal -> RunState "
        "[ctor frozen (1 2)] .\n"
        "  op callEvent : Nat SpectecTerminal SpectecTerminal -> RunState "
        "[ctor frozen (2 3)] .\n"
        "  op callResult : SpectecTerminal SpectecTerminal -> RunState "
        "[ctor frozen (1 2)] .",
    )
    text = once(
        text,
        "  op inputArgs : -> SpectecTerminals .",
        "  op inputArgs : -> SpectecTerminals .\n"
        "  op eventName : -> SpectecTerminal .\n"
        "  op resultName : -> SpectecTerminal .\n"
        "  op eventArgs : Nat -> SpectecTerminals .",
    )
    text = once(
        text,
        "  vars C C2 S MI NAME OTHER ADDR XA : SpectecTerminal .",
        "  vars C C2 S MI NAME OTHER ADDR XA : SpectecTerminal .\n"
        "  vars N : Nat .",
    )

    insert_after_args = (
        "  eq inputArgs = eps .\n"
        f"  eq eventName = {name_term('spacewasm_state_event')} .\n"
        f"  eq resultName = {name_term('spacewasm_state_result')} .\n"
        "  eq eventArgs(N) = num.const(numtype.i32, uN.wrap(N)) ."
    )
    text = once(text, "  eq inputArgs = eps .", insert_after_args)

    old_invoke = """  rl [invoke] :
    init(config.sym(state.sym(S, rec.frame(LOCALS, MI)), eps))
    => exec(def.invoke(
      S, findFunc(value('EXPORTS, MI), inputName), inputArgs)) .
"""
    new_invoke = """  --- Stop after module instantiation. The environment model branches only
  --- after this deterministic prefix has produced the exact store and module.
  rl [prepared] :
    init(config.sym(state.sym(S, rec.frame(LOCALS, MI)), eps))
    => prepared(S, MI) .

  rl [invoke-state-init] : callInit(S, MI) =>
    exec(def.invoke(
      S, findFunc(value('EXPORTS, MI), inputName), inputArgs)) .
  rl [invoke-state-event] : callEvent(N, S, MI) =>
    exec(def.invoke(
      S, findFunc(value('EXPORTS, MI), eventName), eventArgs(N))) .
  rl [invoke-state-result] : callResult(S, MI) =>
    exec(def.invoke(
      S, findFunc(value('EXPORTS, MI), resultName), eps)) .
"""
    text = once(text, old_invoke, new_invoke)

    outer = r'''

mod SPACEWASM-STATEFUL-AUTO-MC is
  protecting SPACEWASM-STATEFUL-EVAL .
  protecting META-LEVEL * (op __ to _metaConcat_) .
  including MODEL-CHECKER .

  sort MCState .
  subsort MCState < State .

  op initial : -> MCState [ctor] .
  op ready : SpectecTerminal SpectecTerminal -> MCState [ctor frozen (1 2)] .
  op one : Nat SpectecTerminal SpectecTerminal -> MCState [ctor frozen (2 3)] .
  op two : Nat Nat SpectecTerminal SpectecTerminal -> MCState [ctor frozen (3 4)] .
  op done : Nat Nat Nat Nat -> MCState [ctor] .

  vars E0 E1 E2 N : Nat .
  vars S S1 S2 S3 S4 MI : SpectecTerminal .
  var X : MCState .

  --- The memo attribute prevents the reachability query and LTL checker from
  --- repeating an already-completed exact production execution.
  op exactPrepare : -> RunState [memo] .
  eq exactPrepare =
    downTerm(
      getTerm(metaRewrite(
        upModule('SPACEWASM-STATEFUL-EVAL, false),
        upTerm(boot), unbounded)),
      boot) .

  op exactInit : SpectecTerminal SpectecTerminal -> RunState [memo] .
  eq exactInit(S, MI) =
    downTerm(
      getTerm(metaRewrite(
        upModule('SPACEWASM-STATEFUL-EVAL, false),
        upTerm(callInit(S, MI)), unbounded)),
      callInit(S, MI)) .

  op exactEvent : Nat SpectecTerminal SpectecTerminal -> RunState [memo] .
  eq exactEvent(E0, S, MI) =
    downTerm(
      getTerm(metaRewrite(
        upModule('SPACEWASM-STATEFUL-EVAL, false),
        upTerm(callEvent(E0, S, MI)), unbounded)),
      callEvent(E0, S, MI)) .

  op exactResult : SpectecTerminal SpectecTerminal -> RunState [memo] .
  eq exactResult(S, MI) =
    downTerm(
      getTerm(metaRewrite(
        upModule('SPACEWASM-STATEFUL-EVAL, false),
        upTerm(callResult(S, MI)), unbounded)),
      callResult(S, MI)) .

  --- Execute the exact module instantiation and state initialization once.
  crl [initialize] : initial => ready(S1, MI)
    if prepared(S, MI) := exactPrepare /\
       exec(config.sym(S1,
         instr.const(numtype.i32, uN.wrap(0)))) := exactInit(S, MI) .

  --- Generic first event choice.
  crl [first-attacker] : ready(S, MI) => one(0, S1, MI)
    if exec(config.sym(S1,
         instr.const(numtype.i32, uN.wrap(0)))) := exactEvent(0, S, MI) .
  crl [first-future] : ready(S, MI) => one(1, S1, MI)
    if exec(config.sym(S1,
         instr.const(numtype.i32, uN.wrap(0)))) := exactEvent(1, S, MI) .
  crl [first-call] : ready(S, MI) => one(2, S1, MI)
    if exec(config.sym(S1,
         instr.const(numtype.i32, uN.wrap(0)))) := exactEvent(2, S, MI) .

  --- Choose any distinct second event.
  crl [second-attacker] : one(E0, S, MI) => two(E0, 0, S1, MI)
    if not (E0 == 0) /\
       exec(config.sym(S1,
         instr.const(numtype.i32, uN.wrap(0)))) := exactEvent(0, S, MI) .
  crl [second-future] : one(E0, S, MI) => two(E0, 1, S1, MI)
    if not (E0 == 1) /\
       exec(config.sym(S1,
         instr.const(numtype.i32, uN.wrap(0)))) := exactEvent(1, S, MI) .
  crl [second-call] : one(E0, S, MI) => two(E0, 2, S1, MI)
    if not (E0 == 2) /\
       exec(config.sym(S1,
         instr.const(numtype.i32, uN.wrap(0)))) := exactEvent(2, S, MI) .

  --- The remaining event ID is 3 - E0 - E1; then read the public result.
  crl [third-and-observe] : two(E0, E1, S, MI) =>
      done(E0, E1, (3 - E0) - E1, N)
    if E2 := (3 - E0) - E1 /\
       exec(config.sym(S1,
         instr.const(numtype.i32, uN.wrap(0)))) := exactEvent(E2, S, MI) /\
       exec(config.sym(S2,
         instr.const(numtype.i32, uN.wrap(N)))) := exactResult(S1, MI) .

  op wrong-provider-result : -> Prop [ctor] .
  ceq done(E0, E1, E2, N) |= wrong-provider-result = true
    if not (N == 7) .
  eq X |= wrong-provider-result = false [owise] .
endm

select SPACEWASM-STATEFUL-AUTO-MC .
search [1] in SPACEWASM-STATEFUL-AUTO-MC :
  initial =>* X:MCState
  such that X:MCState |= wrong-provider-result .
show path labels 1 .
red in SPACEWASM-STATEFUL-AUTO-MC :
  modelCheck(initial, [] ~ wrong-provider-result) .
quit
'''

    return once(text, "endm\n", "endm\n" + outer)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(
        transform(args.input.read_text(encoding="utf-8")), encoding="utf-8"
    )


if __name__ == "__main__":
    main()
